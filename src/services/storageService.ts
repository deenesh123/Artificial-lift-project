// Helper to safely read from localStorage with fallback
function loadFromStorage<T>(key: string, defaultData: T[]): T[] {
  try {
    const raw = localStorage.getItem(key);
    if (!raw) {
      localStorage.setItem(key, JSON.stringify(defaultData));
      return defaultData;
    }
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length > 0) {
      return parsed;
    }
    localStorage.setItem(key, JSON.stringify(defaultData));
    return defaultData;
  } catch (err) {
    console.warn(`Error loading ${key} from storage, using initial data:`, err);
    return defaultData;
  }
}

// Helper to save to localStorage
function saveToStorage<T>(key: string, data: T[]): void {
  try {
    localStorage.setItem(key, JSON.stringify(data));
    // Dispatch window storage event so all tabs/components stay in sync
    window.dispatchEvent(new Event('storage'));
  } catch (err) {
    console.error(`Error saving ${key} to storage:`, err);
  }
}

